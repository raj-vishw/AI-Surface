func newAlertSuppressCommand() *cobra.Command {
	var reason, actorID, durationStr string
	cmd := &cobra.Command{
		Use:   "suppress <alert-id>",
		Short: "Suppress an alert (reason required; evidence is never deleted)",
		Args:  cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			id, err := uuid.Parse(args[0])
			if err != nil {
				return fmt.Errorf("invalid alert id: %w", err)
			}
			if reason == "" || actorID == "" {
				return fmt.Errorf("--reason and --actor are required")
			}
			var duration time.Duration
			if durationStr != "" {
				duration, err = time.ParseDuration(durationStr)
				if err != nil {
					return fmt.Errorf("invalid --duration: %w", err)
				}
			}
			svc, db, err := buildRuleService(cmd)
			if err != nil {
				return err
			}
			defer db.Close()
			a, err := svc.SuppressAlert(cmd.Context(), id, reason, actorID, duration)
			if err != nil {
				return err
			}
			return printAlert(cmd, a)
		},
	}
	cmd.Flags().StringVar(&reason, "reason", "", "why this alert is being suppressed (required)")
	cmd.Flags().StringVar(&actorID, "actor", "", "analyst identifier (required)")
	cmd.Flags().StringVar(&durationStr, "duration", "", "e.g. 30m — omit for indefinite")
	return cmd
}

func newAlertInvestigateCommand() *cobra.Command {
	var actorID string
	cmd := &cobra.Command{
		Use:   "investigate <alert-id>",
		Short: "Promote an alert into a Phase 9 investigation, attaching its evidence and a timeline event automatically",
		Args:  cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			id, err := uuid.Parse(args[0])
			if err != nil {
				return fmt.Errorf("invalid alert id: %w", err)
			}
			if actorID == "" {
				return fmt.Errorf("--actor is required")
			}
			svc, db, err := buildRuleService(cmd)
			if err != nil {
				return err
			}
			defer db.Close()
			inv, err := svc.PromoteToInvestigation(cmd.Context(), id, actorID)
			if err != nil {
				return err
			}
			fmt.Fprintf(cmd.OutOrStdout(), "Created investigation %s (%q).\n", inv.ID, inv.Title) //nolint:errcheck
			return nil
		},
	}
	cmd.Flags().StringVar(&actorID, "actor", "", "analyst identifier (required)")
	return cmd
}
