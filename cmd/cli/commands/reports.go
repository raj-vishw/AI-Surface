func newReportExportCommand() *cobra.Command {
	var format string
	cmd := &cobra.Command{
		Use:   "export <id>",
		Short: "Export a report as JSON or CSV — secrets redacted, values escaped against spreadsheet injection",
		Args:  cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			id, err := uuid.Parse(args[0])
			if err != nil {
				return fmt.Errorf("invalid report id: %w", err)
			}
			svc, db, err := buildReportingService(cmd)
			if err != nil {
				return err
			}
			defer db.Close()
			out, err := svc.Export(cmd.Context(), id, strings.ToLower(format))
			if err != nil {
				return err
			}
			_, err = cmd.OutOrStdout().Write(out)
			return err
		},
	}
	cmd.Flags().StringVar(&format, "format", "json", "json|csv")
	return cmd
}
